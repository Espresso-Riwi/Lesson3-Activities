package Loops;
public class Arrays { 

public static void main(String[] args) {
    // Create an array with 5 integers numbers
    int[] numbers = {1, 2, 3, 4, 5};

    // Iterate through the array with a for loop and display each number multiplied by 2.
    for (int i = 0; i < numbers.length; i++) {
            System.out.println(numbers[i] * 2);
    }
}
}

